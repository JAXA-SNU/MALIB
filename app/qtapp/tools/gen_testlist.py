    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["ID", "分類", "重要度", "試験項目", "事前条件・準備", "手順",
                    "期待結果", "判定", "実測値・所見", "実施日", "実施者",
                    "使用機材", "不具合番号"])
        for c in CASES:
            w.writerow([c[0], c[1], c[6], c[2], c[3], c[4], c[5],
                        "", "", "", "", "", ""])
